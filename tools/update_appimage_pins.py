#!/usr/bin/env python3
"""Regenerate the checksums the AppImage build verifies every download against.

  python tools/update_appimage_pins.py            # after changing python/requirements.txt or a version below
  python tools/update_appimage_pins.py --check    # exit 1 when the pins don't match their inputs

Writes, under appimage/:
  requirements.lock  python/requirements.txt plus every dependency, each with the SHA-256 of all its files on PyPI
  build-tools.lock   python-appimage and its dependencies for the build's own virtualenv
  pins.sh            the Python base image and appimagetool for each architecture, with their SHA-256

Dependencies of the app packages must be pinned exactly by their parents (PySide6 pins its parts); build-tool
dependencies take the newest release their parents allow. Needs network access to pypi.org and api.github.com.
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name
from pip._vendor.packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]
APPIMAGE = ROOT / "appimage"
PYTHON_VERSION = "3.12"              # the Python the AppImage bundles
PYTHON_APPIMAGE_VERSION = "1.4.7"    # the tool that assembles the AppDir
APPIMAGETOOL_VERSION = "1.9.1"       # a numbered release; "continuous" changes without notice
ARCHES = ("x86_64", "aarch64")
HEADER = "# Generated by tools/update_appimage_pins.py; edit the inputs there, not this file.\n"


def fetch_json(url):
    request = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "pin-updater"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def release(name, version):
    data = fetch_json(f"https://pypi.org/pypi/{name}/{version}/json")
    hashes = sorted({f["digests"]["sha256"] for f in data["urls"] if not f.get("yanked")})
    if not hashes:
        raise SystemExit(f"{name} {version} has no files on PyPI")
    return data["info"]["name"], data["info"].get("requires_dist") or [], hashes


def newest(requirement):
    versions = [Version(v) for v, files in fetch_json(f"https://pypi.org/pypi/{requirement.name}/json")["releases"].items()
                if files and not all(f.get("yanked") for f in files)]
    allowed = [v for v in versions if not v.is_prerelease and v in requirement.specifier]
    if not allowed:
        raise SystemExit(f"no release of {requirement.name} satisfies {requirement.specifier}")
    return str(max(allowed))


def resolve(roots, environments, exact):
    """{name: (version, hashes)} for `roots` and their dependencies under any of `environments`."""
    locked, queue = {}, [Requirement(text) for text in roots]
    while queue:
        requirement = queue.pop(0)
        key = canonicalize_name(requirement.name)
        pins = [spec.version for spec in requirement.specifier if spec.operator == "=="]
        if exact and not pins:
            raise SystemExit(f"{requirement} is not pinned with ==; pin it in python/requirements.txt")
        version = pins[0] if pins else newest(requirement)
        if key in locked:
            if locked[key][0] != version:
                raise SystemExit(f"{requirement.name}: both {locked[key][0]} and {version} are required")
            continue
        name, requires, hashes = release(requirement.name, version)
        locked[key] = (version, hashes, name)
        for text in requires:
            dependency = Requirement(text)
            marker = dependency.marker
            if marker is None or any(marker.evaluate({**env, "extra": ""}) for env in environments):
                queue.append(dependency)
    return {key: locked[key] for key in sorted(locked)}


def lock_text(locked, note):
    lines = [HEADER, f"# {note}\n"]
    continued = " \\"
    for version, hashes, name in locked.values():
        lines.append(f"{name}=={version}{continued}\n")
        lines.extend(f"    --hash=sha256:{digest}{continued if i < len(hashes) - 1 else ''}\n"
                     for i, digest in enumerate(hashes))
    return "".join(lines)


def asset_pins():
    """Base image (the oldest-glibc manylinux build, like python-appimage picks) and appimagetool per arch."""
    images = fetch_json(f"https://api.github.com/repos/niess/python-appimage/releases/tags/python{PYTHON_VERSION}")
    tools = fetch_json(f"https://api.github.com/repos/AppImage/appimagetool/releases/tags/{APPIMAGETOOL_VERSION}")
    tag = "cp" + PYTHON_VERSION.replace(".", "")
    lines = [HEADER, f'PINNED_PYTHON_VERSION="{PYTHON_VERSION}"\n']
    for arch in ARCHES:
        pattern = re.compile(rf"^python{re.escape(PYTHON_VERSION)}\.\d+-{tag}-{tag}-manylinux(\w+?)_{arch}\.AppImage$")
        candidates = [(m.group(1), a) for a in images["assets"] if (m := pattern.match(a["name"]))]
        if not candidates:
            raise SystemExit(f"no Python {PYTHON_VERSION} base image for {arch}")
        # "2014" (glibc 2.17) sorts before "_2_28", as in python-appimage's own choice
        image = min(candidates, key=lambda item: item[0])[1]
        tool = next((a for a in tools["assets"] if a["name"] == f"appimagetool-{arch}.AppImage"), None)
        if tool is None:
            raise SystemExit(f"appimagetool {APPIMAGETOOL_VERSION} has no {arch} build")
        for kind, asset in (("BASE_IMAGE", image), ("APPIMAGETOOL", tool)):
            digest = asset.get("digest") or ""
            if not digest.startswith("sha256:"):
                raise SystemExit(f"GitHub reports no SHA-256 for {asset['name']}")
            lines.append(f'{kind}_URL_{arch}="{asset["browser_download_url"]}"\n')
            lines.append(f'{kind}_SHA256_{arch}="{digest[7:]}"\n')
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()

    roots = [line.split("#")[0].strip() for line in (ROOT / "python" / "requirements.txt").read_text().splitlines()]
    roots = [line for line in roots if line]
    target = [{"python_version": PYTHON_VERSION, "python_full_version": PYTHON_VERSION + ".0", "sys_platform": "linux",
               "platform_system": "Linux", "os_name": "posix", "platform_machine": arch,
               "implementation_name": "cpython", "platform_python_implementation": "CPython"} for arch in ARCHES]
    host = [{**env, "python_version": v, "python_full_version": v + ".0"} for env in target for v in
            ("3.11", "3.12", "3.13", "3.14")]
    outputs = {
        "requirements.lock": lock_text(
            resolve(roots, target, exact=True),
            f"Wheels bundled into the AppImage (Python {PYTHON_VERSION}), from python/requirements.txt."),
        "build-tools.lock": lock_text(resolve([f"python-appimage=={PYTHON_APPIMAGE_VERSION}"], host, exact=False),
                                      "The build's own virtualenv (any Python 3.11+ on the build machine)."),
        "pins.sh": asset_pins(),
    }
    stale = []
    for name, text in outputs.items():
        path = APPIMAGE / name
        if path.exists() and path.read_text() == text:
            continue
        stale.append(name)
        if not args.check:
            path.write_text(text)
    if args.check:
        print("stale: " + ", ".join(stale) if stale else "pins are current")
        return 1 if stale else 0
    print("updated: " + ", ".join(stale) if stale else "pins were already current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
